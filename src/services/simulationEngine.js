/**
 * Calculates dynamic Threat Score (0 - 100) based on live simulation metrics
 */
export function calculateThreatScore({ nodes = [], activePhaseIndex = 0, activeControls = {}, blockedCount = 0 }) {
  let score = 20; // baseline ambient threat
  
  // Phase progression impact
  score += Math.min(30, activePhaseIndex * 7);

  // Compromised nodes impact
  const compromised = nodes.filter(n => n.status === 'Compromised');
  score += compromised.length * 16;

  // Critical asset risk
  const criticalCompromised = compromised.filter(n => n.criticality === 'CRITICAL');
  score += criticalCompromised.length * 25;

  // Active defenses mitigate threat
  const activeDefensesCount = Object.values(activeControls).filter(Boolean).length;
  score -= activeDefensesCount * 5;

  // Blocked threats reduce severity
  score -= Math.min(20, blockedCount * 4);

  return Math.max(10, Math.min(99, Math.round(score)));
}

